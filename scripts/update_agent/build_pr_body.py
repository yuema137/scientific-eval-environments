"""Build the automated-PR body from run manifests (no transcripts, no raw dumps)."""
import argparse
import os

from common import read_json


def _maybe(run_dir, rel):
    p = os.path.join(run_dir, rel)
    return read_json(p) if os.path.exists(p) else None


def build(run_dir):
    cov = _maybe(run_dir, "phase1/coverage.json") or {}
    cands = _maybe(run_dir, "phase1/candidates.json") or []
    accepted = _maybe(run_dir, "phase2/accepted.json") or []
    rejected = _maybe(run_dir, "phase2/rejected.json") or []
    tzn = _maybe(run_dir, "phase3/topic_assignments.json") or {}
    dmn = _maybe(run_dir, "phase3/domain_assignments.json") or {}
    act = _maybe(run_dir, "phase3/activity_assignments.json") or {}
    par = _maybe(run_dir, "phase4/parity_validation.json") or {}
    rev = _maybe(run_dir, "phase5/review_manifest.json") or {}
    gate = _maybe(run_dir, "state/final_gate.json") or {}

    L = []
    L.append("## Automated knowledge update")
    L.append("")
    L.append("_Generated by the Daily Update Agent. Every phase passed the deterministic gates; "
             "a human reviewer makes the final editorial decision — this PR is never auto-merged._")
    L.append("")
    rel = (_maybe(run_dir, "phase1/relevance.json") or {}).get("report", {})
    rbs = cov.get("raw_by_source", {})
    win = cov.get("search_window", {})
    reviewed = len(accepted) + len(rejected)
    acc_rate = (100.0 * len(accepted) / reviewed) if reviewed else 0.0
    L.append("### Discovery funnel")
    L.append("```")
    L.append("Window        %s → %s" % ((win.get("start") or "?")[:10], (win.get("end") or "?")[:10]))
    L.append("Raw           arXiv %-4d OpenReview %-3d GitHub %-4d  (total %d)"
             % (rbs.get("arxiv", 0), rbs.get("openreview", 0), rbs.get("github", 0), cov.get("raw_hit_count", 0)))
    L.append("Prefilter     %d" % (len(cands) if not rel else rel.get("admitted", len(cands))))
    if rel:
        L.append("Relevance     deep_review %d  uncertain %d (admitted %d, github-only excluded %d)  rejected %d"
                 % (rel.get("deep_review", 0), rel.get("uncertain_total", 0), rel.get("uncertain_admitted", 0),
                    rel.get("uncertain_github_only_excluded", 0), rel.get("rejected_low_relevance", 0)))
    L.append("Sent to Phase 2  %d" % len(cands))
    L.append("Deep review   accepted %d   rejected %d   (acceptance %.0f%%)" % (len(accepted), len(rejected), acc_rate))
    L.append("```")
    L.append("_Acceptance rate is the discovery-precision proxy — watch it drift across runs._")
    L.append("")
    if accepted:
        L.append("### Added works")
        for a in accepted:
            L.append("- **%s** (`%s`)" % (a.get("card_title", a.get("card_slug")), a.get("card_slug")))
        L.append("")
    L.append("### English integration")
    L.append("- Topic pages updated: %s" % ", ".join(tzn.get("pages_edited", []) or ["—"]))
    L.append("- Domain pages updated: %s" % ", ".join(dmn.get("pages_edited", []) or ["—"]))
    L.append("- Activity pages updated: %s" % ", ".join(act.get("pages_edited", []) or ["—"]))
    L.append("")
    L.append("### Chinese mirror")
    L.append("- Cards + pages synchronized: %s" % (par.get("files") and len(par["files"]) or "see parity gate"))
    L.append("")
    L.append("### Chinese editorial review")
    L.append("- Files reviewed: %s; wording corrections applied: %s"
             % (rev.get("reviewed", "?"), rev.get("edited", "?")))
    L.append("")
    L.append("### Validation")
    for k in ("discovery", "cards", "english_axes", "chinese_mirror", "chinese_review", "final_validation"):
        L.append("- %s: %s" % (k, gate.get(k, "?")))
    L.append("")
    if rejected:
        L.append("<details><summary>Rejected candidates (%d)</summary>" % len(rejected))
        L.append("")
        for r in rejected[:60]:
            L.append("- %s — %s" % (r.get("card_title") or r.get("title", "?"), r.get("reason", "")))
        L.append("")
        L.append("</details>")
    L.append("")
    L.append("🤖 Generated by the Daily Update Agent — see `automation/update_agent/README.md`.")
    return "\n".join(L)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-dir", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    open(a.out, "w").write(build(a.run_dir))
    print("wrote", a.out)
